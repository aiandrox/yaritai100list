/**
 * 文字数と件数の上限。**サーバー・クライアント・画像生成の3箇所で同じ値を使う。**
 *
 * ここを唯一の情報源にする。画面側だけで制限すると API を直接叩かれたときに通るし、
 * 画像生成側だけで制限してもレイアウトが崩れた後になる。
 */

/**
 * リストのタイトルの最大文字数。旧実装と同じ 15。
 *
 * **暫定値。** 画像出力（横長 4列×25行）の見出しとして収まる長さかは、
 * 実際にレンダリングしてから見直す（#9）。
 */
export const LIST_TITLE_MAX_LENGTH = 15

/**
 * 項目本文の最大文字数。旧実装と同じ 22。
 *
 * **暫定値。** 画像出力で番号の右に置くテキストなので、
 * 4列に並べたときの折り返しを見て見直す（#9）。
 */
export const ITEM_TEXT_MAX_LENGTH = 22

/**
 * 1ユーザーが持てるリストの数。`PRODUCT_SPEC.md` §7 暫定 #5。
 *
 * DB の制約でも守る（#6）。アプリのコードだけに頼らない。
 */
export const LISTS_PER_USER_MAX = 5

/**
 * 1リストが持てる項目の数。
 *
 * 100 は**上限かつ目標**であり、固定枠ではない（`PRODUCT_SPEC.md` §3）。
 * データとして100個の空スロットを持つ設計にはしない。
 */
export const ITEMS_PER_LIST_MAX = 100
