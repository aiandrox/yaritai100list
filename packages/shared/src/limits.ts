/**
 * 文字数と件数の上限。**サーバー・クライアント・画像生成の3箇所で同じ値を使う。**
 *
 * ここを唯一の情報源にする。画面側だけで制限すると API を直接叩かれたときに通るし、
 * 画像生成側だけで制限してもレイアウトが崩れた後になる。
 */

/**
 * リストのタイトルの最大文字数。**30**（2026-08-08、#146）。
 *
 * 旧実装と同じ 15 から伸ばした。**短すぎて言いたいことが入らなかった**（利用者の指摘）。
 * 「2026年に絶対やりたいことリスト」で 16 文字なので、15 では日常的に足りない。
 *
 * 30 にした根拠は画面の幅。編集画面は `max-w-xl`（36rem、#143）で、
 * タイトルの入力欄は `text-xl`。広い画面なら 30 文字弱が1行に収まる。
 * ⚠️ **電話では1行に収まらない。** 入力欄は折り返さないので横に流れる
 * （一覧では `truncate` で切る）。**読めなくなるわけではない**ので許容した。
 *
 * **画像出力（#9）で収まらない場合は、上限を戻さない**（2026-08-08 決定、#146）。
 * 文字を小さくするか、末尾を「…」で切る。
 * **入力できる長さを画像の都合で決めない**、という向きにしてある（詳細は #9）。
 */
export const LIST_TITLE_MAX_LENGTH = 30

/**
 * 項目本文の最大文字数。旧実装と同じ 22。
 *
 * **暫定値。** 画像出力で番号の右に置くテキストなので、
 * 4列に並べたときの折り返しを見て見直す（#9）。
 */
export const ITEM_TEXT_MAX_LENGTH = 22

/**
 * 1ユーザーが持てるリストの数。`PRODUCT_SPEC.md` §7 暫定 #5。
 *
 * DB の制約でも守る（#6）。アプリのコードだけに頼らない。
 */
export const LISTS_PER_USER_MAX = 5

/**
 * 1リストが持てる項目の数。
 *
 * 100 は**上限かつ目標**であり、固定枠ではない（`PRODUCT_SPEC.md` §3）。
 * データとして100個の空スロットを持つ設計にはしない。
 */
export const ITEMS_PER_LIST_MAX = 100

/**
 * 取り入れ面（`/discover`）の1ページに出す本文の数。
 *
 * 100 は「1リストに書ける数」と同じ値だが、**別の理由で決めている**
 * （こちらは1ページで眺めきれる量。あちらは1リストの枠）。
 * 揃えたのは偶然なので、片方を変えるときにもう片方を釣られて変えないこと。
 */
export const DISCOVER_PAGE_SIZE = 100

/**
 * 取り入れ面で開けるページの上限。
 *
 * ⚠️ **飛ばす件数（`offset`）が大きいほど問い合わせが重くなる。**
 * SQLite は飛ばす分も数え上げるので、`?page=100000` を投げられると
 * **プール全体を走査したうえで0件を返す**ことになる。
 *
 * 50 ページ = 5000 件。**眺めて選ぶ場所としては十分すぎる**ので、ここで切る。
 */
export const DISCOVER_MAX_PAGE = 50
