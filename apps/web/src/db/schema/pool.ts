import { index, integer, sqliteTable, text } from 'drizzle-orm/sqlite-core'

/**
 * 取り入れ面に出す一覧（#254 / 親 #252）。**バッチが作り直す派生データ。**
 *
 * 🔴 **ここに書き込むのはバッチだけ**（`src/pool.ts` の `rebuildPool`）。
 * 画面からの操作でこの表が変わることは無い。消えても次のバッチで元に戻る。
 *
 * 🔴 **`/discover` はこの表を読むだけにする。** 以前は要求のたびに
 * `items` を `group by text` して人数を数えていた。**開くたびに全項目を走査する**ので、
 * 項目が増えるほど重くなるうえ、表記ゆれが別の行として並んでいた。
 *
 * ⚠️ **リアルタイムではない。** 全公開をやめた本文は次のバッチまで残る。
 * 「おおまかにどんなことが書かれているかを知る場所」なので、これでよい
 * （2026-08-10 の利用者の判断）。**個人名などは AI 判定で落としてある**（#253）ので、
 * 遅れて消えることが漏洩にならない、というのが成り立つ前提。
 */
export const pool = sqliteTable(
  'pool',
  {
    /**
     * 代表表現（`wish_texts.canonical`）。**名寄せの単位であり、画面に出る本文。**
     *
     * 「富士山に登りたい」「富士山登頂」はどちらも `富士山に登る` に寄せてある。
     * だから**書いた人の本文がそのまま出るとは限らない。**
     */
    canonical: text('canonical').primaryKey(),

    /** ジャンル（`GENRES` のスラッグ）。ジャンル別の入口は #255。 */
    genre: text('genre').notNull(),

    /**
     * その代表表現を書いている人の数。
     *
     * 🔴 **応答に入れない**（#241）。数えるのは**非公開リストも含めた全リスト**なので、
     * 出すと「知りたい本文を自分の全公開リストに書く → プールに出る → 人数を読む」で
     * **何人が非公開でそれを持っているかを問い合わせられる。**
     * 並べるためだけに持つ。
     */
    writers: integer('writers').notNull(),
  },
  (t) => [
    /**
     * 人気順に並べるため。
     *
     * ⚠️ **`order by writers desc, canonical asc` を索引だけで満たせるわけではない**
     * （向きが揃っていないので、SQLite は最後に並べ替える）。
     * それでも**全行を読んでから数え直す**よりは軽い。
     * プールは高々数千行なので、ここを詰めるのは実際に重くなってからでよい。
     */
    index('pool_writers_idx').on(t.writers),
  ],
)
